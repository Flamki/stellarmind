/**
 * Offline scoring and the reviewable report (issue #154).
 *
 * The offline report is deterministic: it contains no timestamps, absolute
 * paths or environment details, key order is fixed, and line endings are LF,
 * so two runs over the same checkout are byte-identical and the report can be
 * committed as a baseline and compared in review.
 */
import { runProperty } from './checks.js'
import { reviewStatus } from './reviews.js'

export const REPORT_VERSION = 1

function contextFor(testCase) {
  return { input: testCase.task, context: testCase.context || {} }
}

/** Run every property of a case against one output text. */
export function scoreText(testCase, text) {
  const ctx = contextFor(testCase)
  const properties = testCase.properties.map((property) => runProperty(property, text, ctx))
  return {
    passed: properties.filter((p) => p.pass).length,
    total: properties.length,
    properties,
  }
}

function sameSet(a, b) {
  return a.length === b.length && a.every((value) => b.includes(value))
}

function scoreCase(testCase, revisions, evalSetVersion, reviews) {
  const revision = revisions[testCase.agent]
  const reference = scoreText(testCase, testCase.fixtureTexts.pass)

  const negativeFixtures = testCase.fixtures.negative.map((negative, index) => {
    const scored = scoreText(testCase, testCase.fixtureTexts.negative[index])
    const actualFailures = scored.properties.filter((p) => !p.pass).map((p) => p.id)
    return {
      file: negative.file,
      note: negative.note,
      expectedFailures: negative.expectFail,
      actualFailures,
      rejectedAsExpected: sameSet(negative.expectFail, actualFailures),
    }
  })

  const review = reviewStatus(
    testCase.id,
    { evalSetVersion, promptRevision: revision.promptRevision },
    reviews
  )

  return {
    id: testCase.id,
    agent: testCase.agent,
    phase: testCase.phase,
    task: testCase.task,
    revision: { model: revision.model, promptRevision: revision.promptRevision },
    automated: {
      referencePassed: reference.passed === reference.total,
      passed: reference.passed,
      total: reference.total,
      properties: reference.properties,
    },
    negativeFixtures,
    humanReview: {
      status: review.status,
      questions: testCase.humanReview,
      latest: review.latest,
    },
  }
}

/**
 * @param {{ set: object, cases: object[], digest: string }} loaded
 * @param {object} revisions from currentRevisions()
 * @param {object[]} reviews from loadReviews()
 */
export function buildReport(loaded, revisions, reviews = []) {
  const { set, cases, digest } = loaded
  const scored = cases.map((testCase) => scoreCase(testCase, revisions, set.version, reviews))

  const negatives = scored.flatMap((c) => c.negativeFixtures)
  const humanCounts = { accept: 0, 'needs-work': 0, stale: 0, 'not recorded': 0 }
  for (const c of scored) humanCounts[c.humanReview.status] += 1

  const healthy =
    scored.every((c) => c.automated.referencePassed) && negatives.every((n) => n.rejectedAsExpected)

  return {
    reportVersion: REPORT_VERSION,
    evalSet: { name: set.evalSet, version: set.version, digest },
    source: 'offline-fixtures',
    sourceNote:
      'Hand-written reference outputs. No model was called and no key or network was used.',
    revisions,
    summary: {
      status: healthy ? 'pass' : 'fail',
      cases: scored.length,
      automated: {
        properties: scored.reduce((sum, c) => sum + c.automated.total, 0),
        passed: scored.reduce((sum, c) => sum + c.automated.passed, 0),
        referenceOutputsFullyPassing: scored.filter((c) => c.automated.referencePassed).length,
      },
      negativeFixtures: {
        total: negatives.length,
        rejectedAsExpected: negatives.filter((n) => n.rejectedAsExpected).length,
      },
      humanReview: {
        accepted: humanCounts.accept,
        needsWork: humanCounts['needs-work'],
        stale: humanCounts.stale,
        notRecorded: humanCounts['not recorded'],
      },
    },
    cases: scored,
  }
}

export function renderJson(report) {
  return `${JSON.stringify(report, null, 2)}\n`
}

const MARK = { true: 'pass', false: 'FAIL' }

function cell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function revisionLabel(value) {
  return value === null ? 'none' : `\`${value}\``
}

export function renderMarkdown(report) {
  const { evalSet, summary } = report
  const lines = []
  const push = (...rows) => lines.push(...rows)

  push(
    '# Agent quality evaluation report',
    '',
    '<!-- Generated by `npm run eval:accept`. Do not edit by hand. -->',
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Eval set | ${evalSet.name} ${evalSet.version} |`,
    `| Content digest | \`${evalSet.digest}\` |`,
    `| Output source | ${cell(report.sourceNote)} |`,
    `| Suite status | **${summary.status.toUpperCase()}** |`,
    '',
    '## Revisions under evaluation',
    '',
    'These are the model and prompt revisions configured in the code at the time of the report. A',
    'revision changes only when the wording or model changes, so a different value here means the',
    'recorded baseline and any human reviews need another look.',
    '',
    '| Agent | Model | Fallback model | Prompt revision |',
    '| --- | --- | --- | --- |'
  )
  for (const [agent, rev] of Object.entries(report.revisions)) {
    push(
      `| ${agent} | \`${rev.model}\` | ${rev.fallbackModel ? `\`${rev.fallbackModel}\`` : 'none'} | ${revisionLabel(rev.promptRevision)} |`
    )
  }
  push('', 'The planner prompt is built inline in `orchestrator.js` and has no revision yet.', '')

  push(
    '## Automated structural checks (machine-scored)',
    '',
    `- Properties passing on reference outputs: ${summary.automated.passed} of ${summary.automated.properties}`,
    `- Cases whose reference output passes every property: ${summary.automated.referenceOutputsFullyPassing} of ${summary.cases}`,
    `- Deliberately incomplete outputs rejected for exactly the expected reasons: ${summary.negativeFixtures.rejectedAsExpected} of ${summary.negativeFixtures.total}`,
    '',
    'These checks verify structure only (sections, counts, figures kept, plan validity). They say',
    'nothing about whether an answer is true or useful.',
    '',
    '| Case | Agent | Phase | Properties | Incomplete outputs rejected |',
    '| --- | --- | --- | --- | --- |'
  )
  for (const c of report.cases) {
    const rejected = c.negativeFixtures.filter((n) => n.rejectedAsExpected).length
    push(
      `| ${c.id} | ${c.agent} | ${c.phase} | ${c.automated.passed}/${c.automated.total} | ${rejected}/${c.negativeFixtures.length} |`
    )
  }

  push(
    '',
    '## Human judgment (not scored by this tool)',
    '',
    `- Accepted: ${summary.humanReview.accepted}, needs work: ${summary.humanReview.needsWork}, stale: ${summary.humanReview.stale}, not recorded: ${summary.humanReview.notRecorded}`,
    '',
    'Quality questions that need a person are listed per case. Judgments are recorded by hand in',
    '`evals/reviews.v1.json`; this tool never infers them. A review goes stale when the eval set',
    'version or the prompt revision it judged changes.',
    '',
    '| Case | Review status | Questions for a reviewer |',
    '| --- | --- | --- |'
  )
  for (const c of report.cases) {
    push(`| ${c.id} | ${c.humanReview.status} | ${cell(c.humanReview.questions.join(' / '))} |`)
  }

  push('', '## Case details')
  for (const c of report.cases) {
    push(
      '',
      `### ${c.id}`,
      '',
      `- Agent: ${c.agent} (${c.phase})`,
      `- Model: \`${c.revision.model}\``
    )
    push(`- Prompt revision: ${revisionLabel(c.revision.promptRevision)}`)
    push('', '| Property | Check | Result | Detail |', '| --- | --- | --- | --- |')
    for (const p of c.automated.properties) {
      push(`| ${p.id} | ${p.check} | ${MARK[p.pass]} | ${cell(p.detail)} |`)
    }
    push('', 'Deliberately incomplete outputs:', '')
    for (const n of c.negativeFixtures) {
      push(
        `- \`${n.file}\` (${n.note}) fails: ${n.actualFailures.join(', ')}${
          n.rejectedAsExpected ? '' : ' - DOES NOT MATCH EXPECTATION'
        }`
      )
    }
  }
  return `${lines.join('\n')}\n`
}
